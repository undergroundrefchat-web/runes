// Таро Уэйта–Смит, рисунки Памелы Колман Смит, издание 1909 года («Roses & Lilies»).
// Рисунки — общественное достояние (опубликованы в 1909, художница умерла в 1951).
// Сканы: Wikimedia Commons, категория «Rider-Waite tarot deck (Roses & Lilies)».
// Картинка карты: img/waite/<id>.webp
//   m00…m21          — старшие арканы
//   wands01…wands14  — масть; 11 паж, 12 рыцарь, 13 королева, 14 король

const MAJOR = ['Шут', 'Маг', 'Верховная Жрица', 'Императрица', 'Император', 'Иерофант', 'Влюблённые',
  'Колесница', 'Сила', 'Отшельник', 'Колесо Фортуны', 'Справедливость', 'Повешенный', 'Смерть',
  'Умеренность', 'Дьявол', 'Башня', 'Звезда', 'Луна', 'Солнце', 'Суд', 'Мир'];
const ROMAN = ['0', 'I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII', 'XIII',
  'XIV', 'XV', 'XVI', 'XVII', 'XVIII', 'XIX', 'XX', 'XXI'];

export const SUITS = [
  { id: 'wands', name: 'Жезлы', of: 'Жезлов' },
  { id: 'cups', name: 'Кубки', of: 'Кубков' },
  { id: 'swords', name: 'Мечи', of: 'Мечей' },
  { id: 'pentacles', name: 'Пентакли', of: 'Пентаклей' },
];
const RANK = ['Туз', 'Двойка', 'Тройка', 'Четвёрка', 'Пятёрка', 'Шестёрка', 'Семёрка', 'Восьмёрка',
  'Девятка', 'Десятка', 'Паж', 'Рыцарь', 'Королева', 'Король'];

const pad = n => String(n).padStart(2, '0');

export const WAITE = [
  ...MAJOR.map((name, n) => ({ id: `m${pad(n)}`, name, suit: null, num: ROMAN[n] })),
  ...SUITS.flatMap(s => RANK.map((r, k) => ({ id: `${s.id}${pad(k + 1)}`, name: `${r} ${s.of}`, suit: s.id }))),
];
